test('temp and config folder edits are not places', async () => {
  const { claude, alpha } = setup();
  const t = new Transcript(claude, alpha);
  t.prompt('write a scratch note');
  t.write('/private/tmp/scratch-note.md', 'x');
  t.write(path.join(claude, 'projects', 'x', 'memory', 'note.md'), 'x');
  t.edit(path.join(alpha, 'src/a.ts'));
  t.save();
  const s = newState(t.id, t.file);
  await scan(s, claude);
  const c = deriveCards(s)[0];
  assert.deepEqual(c.files, [path.join(alpha, 'src/a.ts')]);
  assert.deepEqual(c.places.map((p) => p.path), [alpha]);
});

test('places for files with no git and no marker fall back to the project folder', async () => {
  const { root, claude, code } = setup();
  const gone = path.join(code, 'projects', 'gone-app');
  const marked = path.join(code, 'projects', 'marked');
  fs.mkdirSync(path.join(marked, 'web'), { recursive: true });
  fs.writeFileSync(path.join(marked, 'package.json'), '{}');
  const t = new Transcript(claude, code);
  t.prompt('work on the gone app');
  t.edit(path.join(gone, 'src', 'a.ts'));
  t.edit(path.join(gone, 'web', 'b.css'));
  t.edit(path.join(gone, 'README.md'));
  t.prompt('and the marked one');
  t.edit(path.join(marked, 'web', 'c.ts'));
  t.edit(path.join(marked, 'web', 'd.ts'));
  t.edit(path.join(marked, 'e.ts'));
  t.save();
  const s = newState(t.id, t.file);
  await scan(s, claude);
  const cards = deriveCards(s);
  assert.deepEqual(cards.map((c) => c.place).sort(), [gone, marked].sort());
  assert.ok(cards.every((c) => !c.git));
  assert.ok(root);
});
