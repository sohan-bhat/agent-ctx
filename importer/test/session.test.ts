import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { scratch, makeRepo, Transcript } from './synth.ts';
import { newState, scan, deriveCards } from '../src/session.ts';
import { clearPlaceCache } from '../src/place.ts';

function setup() {
  const root = scratch('session');
  const claude = path.join(root, 'claude');
  const code = path.join(root, 'code');
  const alpha = makeRepo(path.join(code, 'alpha'), 'git@github.com:someone/alpha-engine.git');
  const beta = makeRepo(path.join(code, 'beta'), 'https://github.com/someone/beta-site.git');
  fs.mkdirSync(path.join(alpha, 'src'), { recursive: true });
  fs.mkdirSync(path.join(beta, 'web'), { recursive: true });
  clearPlaceCache();
  return { root, claude, code, alpha, beta };
}

test('builds a card from a synthetic transcript', async () => {
  const { claude, alpha } = setup();
  const t = new Transcript(claude, alpha);
  t.noise();
  t.prompt('Add a retry loop to the fetch client in alpha');
  t.meta('Caveat: local command output follows');
  t.notification('background task finished');
  t.reply('Looking at the client now.', { input: 10, read: 1000, write: 200 });
  t.read(path.join(alpha, 'src/client.ts'), 'export const client = 1;');
  t.edit(path.join(alpha, 'src/client.ts'));
  t.edit(path.join(alpha, 'src/retry.ts'));
  t.title('Retry loop for alpha client');
  t.prompt('Now make the backoff exponential with jitter');
  t.edit(path.join(alpha, 'src/retry.ts'));
  t.compact(150000, 20000, [], 'The user asked for a retry loop with exponential backoff. Files src/retry.ts and src/client.ts changed.');
  t.prompt('Write tests for the retry helper, my key is sk-ant-api03-ZZZZZZZZZZabc123DEF456ghi789');
  t.save();
  const s = newState(t.id, t.file);
  const r = await scan(s, claude);
  assert.equal(r.bad, 0);
  const cards = deriveCards(s);
  assert.equal(cards.length, 1);
  const c = cards[0];
  assert.equal(c.place, alpha);
  assert.equal(c.git, true);
  assert.equal(c.project, 'alpha');
  assert.equal(c.remote, 'someone/alpha-engine');
  assert.equal(c.title, 'Retry loop for alpha client');
  assert.equal(c.firstPrompt, 'Add a retry loop to the fetch client in alpha');
  assert.equal(c.prompts.length, 2);
  assert.ok(!JSON.stringify(c).includes('sk-ant-api03'));
  assert.equal(c.summaries.length, 1);
  assert.ok(c.summaries[0].startsWith('The user asked for a retry loop'));
  assert.ok(!c.summaries[0].includes('continued from a previous'));
  assert.deepEqual(c.files.slice(0, 2).sort(), [path.join(alpha, 'src/client.ts'), path.join(alpha, 'src/retry.ts')].sort());
  assert.equal(c.files[0], path.join(alpha, 'src/retry.ts'));
  assert.equal(c.turns, 3);
  assert.ok(c.first < c.last);
});

test('scans incrementally from the stored offset and skips a partial line', async () => {
  const { claude, alpha } = setup();
  const t = new Transcript(claude, alpha);
  t.prompt('first prompt about parsers');
  t.save();
  const s = newState(t.id, t.file);
  await scan(s, claude);
  const off1 = s.offset;
  assert.equal(off1, fs.statSync(t.file).size);
  t.prompt('second prompt about lexers');
  t.save();
  fs.appendFileSync(t.file, '{"type":"user","message":{"role":"user","content":"half writ');
  await scan(s, claude);
  assert.ok(s.offset > off1);
  assert.ok(s.offset < fs.statSync(t.file).size);
  assert.equal(s.turns.length, 2);
  assert.equal(s.turns[1].prompt, 'second prompt about lexers');
});

test('a session that works in two repos from a parent folder makes one card per place', async () => {
  const { claude, code, alpha, beta } = setup();
  const t = new Transcript(claude, code);
  t.prompt('Fix the parser in alpha');
  t.edit(path.join(alpha, 'src/parser.ts'));
  t.edit(path.join(alpha, 'src/parser.ts'));
  t.edit(path.join(alpha, 'src/lexer.ts'));
  t.prompt('Also check the readme');
  t.compact(100000, 15000, [], 'Fixed the alpha parser and lexer.');
  t.prompt('Now style the beta landing page');
  t.edit(path.join(beta, 'web/landing.css'));
  t.edit(path.join(beta, 'web/landing.css'));
  t.prompt('Back to alpha, add a test for the lexer');
  t.edit(path.join(alpha, 'src/lexer.test.ts'));
  t.prompt('And finish the beta hero');
  t.edit(path.join(beta, 'web/hero.tsx'));
  t.compact(120000, 18000, [], 'Styled the beta landing page and hero, added an alpha lexer test.');
  t.prompt('Thanks, wrap up');
  t.save();
  const s = newState(t.id, t.file);
  await scan(s, claude);
  const cards = deriveCards(s);
  assert.equal(cards.length, 2);
  const a = cards.find((c) => c.place === alpha)!;
  const b = cards.find((c) => c.place === beta)!;
  assert.ok(a && b);
  assert.equal(a.id, `${t.id}:1`);
  assert.equal(b.id, `${t.id}:2`);
  assert.deepEqual(a.places.map((p) => p.path).sort(), [alpha, beta, code].sort());
  const parent = a.places.find((p) => p.path === code)!;
  assert.equal(parent.prompts, 6);
  assert.equal(parent.edits, 0);
  assert.equal(a.places.find((p) => p.path === alpha)!.edits, 4);
  assert.equal(b.places.find((p) => p.path === beta)!.edits, 3);
  assert.deepEqual(a.firstPrompt, 'Fix the parser in alpha');
  assert.ok(a.prompts.includes('Also check the readme'));
  assert.ok(a.prompts.includes('Back to alpha, add a test for the lexer'));
  assert.equal(b.firstPrompt, 'Now style the beta landing page');
  assert.ok(b.prompts.includes('And finish the beta hero'));
  assert.ok(b.prompts.includes('Thanks, wrap up'));
  assert.ok(a.files.every((f) => f.startsWith(alpha)));
  assert.ok(b.files.every((f) => f.startsWith(beta)));
});

test('a compaction summary goes to every place that worked in the span it covers', async () => {
  const { claude, code, alpha, beta } = setup();
  const t = new Transcript(claude, code);
  t.prompt('Fix the parser in alpha');
  t.edit(path.join(alpha, 'src/parser.ts'));
  t.edit(path.join(alpha, 'src/parser.ts'));
  t.edit(path.join(alpha, 'src/lexer.ts'));
  t.compact(100000, 15000, [], 'ONLY ALPHA SPAN');
  t.prompt('Now style the beta landing page');
  t.edit(path.join(beta, 'web/landing.css'));
  t.edit(path.join(beta, 'web/landing.css'));
  t.edit(path.join(beta, 'web/hero.tsx'));
  t.prompt('Back to alpha for one more fix');
  t.edit(path.join(alpha, 'src/parser.ts'));
  t.compact(120000, 18000, [], 'BOTH PLACES SPAN');
  t.save();
  const s = newState(t.id, t.file);
  await scan(s, claude);
  const cards = deriveCards(s);
  const a = cards.find((c) => c.place === alpha)!;
  const b = cards.find((c) => c.place === beta)!;
  assert.deepEqual(a.summaries, ['ONLY ALPHA SPAN', 'BOTH PLACES SPAN']);
  assert.deepEqual(b.summaries, ['BOTH PLACES SPAN']);
});

test('a single place with few side edits stays one card filed under the place with most edits', async () => {
  const { claude, code, alpha, beta } = setup();
  const t = new Transcript(claude, code);
  t.prompt('Refactor the alpha engine');
  for (let i = 0; i < 5; i++) t.edit(path.join(alpha, `src/m${i}.ts`));
  t.prompt('Tweak one beta file');
  t.edit(path.join(beta, 'web/a.css'));
  t.edit(path.join(beta, 'web/b.css'));
  t.save();
  const s = newState(t.id, t.file);
  await scan(s, claude);
  const cards = deriveCards(s);
  assert.equal(cards.length, 1);
  assert.equal(cards[0].place, alpha);
  assert.equal(cards[0].id, t.id);
  assert.equal(cards[0].files.length, 7);
});

